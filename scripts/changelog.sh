#!/usr/bin/env bash
# Keeps CHANGELOG.md with git-cliff (config: .cliff.toml), from Conventional Commits.
#   scripts/changelog.sh                  # preview the unreleased changes (writes nothing)
#   scripts/changelog.sh release          # add the next version's section to CHANGELOG.md
#   scripts/changelog.sh release v1.2.0   # ...for a version you choose
#   scripts/changelog.sh notes [v1.2.0]   # print a release's section, for the GitHub release
#   scripts/changelog.sh full             # rebuild the whole file from the history
#
# release works out the next version from the commits since the last version tag (a feat
# raises the minor version, fixes the patch, a breaking change the major), adds its section
# below the header and leaves the rest of the file as it is, hand-written sections included.
# Then commit CHANGELOG.md and tag that commit with the version.
#
# full replaces everything, including hand-written sections such as 1.0.0's.
set -euo pipefail
cd "$(dirname "$0")/.."

file=CHANGELOG.md
usage() { sed -n '3,7p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 2; }

# Lists the commits git-cliff left out (build, chore, ci and style ones), from its verbose log.
skipped() { grep 'Skipping commit' | sed -E 's/^.*Grouping error: //; s/`Skipping commit`/Left out:/' >&2 || true; }

# The section for $1 (e.g. v1.2.0 or 1.2.0) in CHANGELOG.md, or the newest one if $1 is empty:
# from its "## [" heading up to the next one or the end of the releases.
section() {
    local want="${1#v}"
    awk -v want="$want" '
        /^## \[/ {
            if (found) exit
            v = $0; sub(/^## \[/, "", v); sub(/\].*/, "", v)
            if (v != "Unreleased" && (want == "" || v == want)) found = 1
        }
        /^<!-- generated by git-cliff -->/ || /^\[[^]]+\]: / { if (found) exit }
        found { print }
    ' "$file"
}

mode="${1:-preview}"
case "$mode" in
    preview)
        [ $# -le 1 ] || usage
        git cliff --unreleased --strip all -vv 2> >(skipped)
        ;;

    release)
        [ $# -le 2 ] || usage
        [ -f "$file" ] || { echo "No $file yet; make it first (scripts/changelog.sh full, or by hand)." >&2; exit 1; }
        version="${2:-$(git cliff --bumped-version 2>/dev/null)}"
        version="v${version#v}"
        [[ "$version" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "Not a version: $version (use e.g. v1.2.0)." >&2; exit 1; }
        if git rev-parse -q --verify "refs/tags/$version" >/dev/null; then
            # git-cliff suggests the last version again when nothing came after it.
            [ -n "${2:-}" ] || { echo "Nothing new since $version." >&2; exit 1; }
            echo "$version is already tagged." >&2; exit 1
        fi
        if grep -q "^## \[${version#v}\]" "$file"; then
            echo "$file already has a section for ${version#v}." >&2; exit 1
        fi
        grep -q '^---$' "$file" || { echo "$file has no '---' line after its header to add below." >&2; exit 1; }

        new=$(git cliff --unreleased --tag "$version" --strip all -vv 2> >(skipped))
        # Just the heading means no commit since the last tag went in a group.
        if [ "$(grep -c '^- ' <<<"$new")" -eq 0 ]; then
            echo "Nothing to add: no listed changes since the last version tag." >&2; exit 1
        fi
        # Below the header's first "---" line, keeping everything after it as it is.
        at=$(grep -n -m1 '^---$' "$file" | cut -d: -f1)
        tmp=$(mktemp)
        trap 'rm -f "$tmp"' EXIT
        {
            head -n "$at" "$file"
            echo
            sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' <<<"$new"   # without trailing blank lines
            echo
            tail -n +"$((at + 1))" "$file" | sed '/./,$!d'      # without leading blank lines
        } >"$tmp"
        mv "$tmp" "$file"
        trap - EXIT
        echo "Added ${version#v} to $file:" >&2
        echo >&2
        section "$version"
        echo >&2
        echo "Next: commit $file, then tag that commit:  git tag $version" >&2
        ;;

    notes)
        [ $# -le 2 ] || usage
        [ -f "$file" ] || { echo "No $file." >&2; exit 1; }
        out=$(section "${2:-}")
        [ -n "$out" ] || { echo "No section for ${2:-a release} in $file." >&2; exit 1; }
        # Without the "## [x.y.z] - date" heading: the GitHub release has its own title.
        tail -n +2 <<<"$out" | sed '/./,$!d'
        ;;

    full)
        [ $# -le 1 ] || usage
        git cliff -vv -o "$file" 2> >(skipped)
        echo "Rebuilt $file from the whole history." >&2
        ;;

    -h|--help) usage ;;
    *) usage ;;
esac
